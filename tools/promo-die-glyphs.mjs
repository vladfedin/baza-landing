#!/usr/bin/env node
/**
 * promo-die-glyphs.mjs — грани промо-кубика лендинга (js/dice.js, шестой бросок)
 * из исходников приложения, а не руками: те же векторы, что у логотип-кубика
 * beta (magicorp-vtt client/src/components/LogoDie.tsx — P, маски, свиток;
 * logo-die-glyphs.ts — пул случайных глифов; LoadingScreen.tsx — их пути).
 *
 *   node tools/promo-die-glyphs.mjs [путь к magicorp-vtt]
 *
 * Пишет www/js/promo-die-glyphs.js (window.RB_PROMO_DIE). Изменился логотип
 * или пул в приложении — перезапустить.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const APP = resolve(process.argv[2] ?? new URL('../../magicorp-vtt', import.meta.url).pathname);
const comp = (f) => readFileSync(join(APP, 'client/src/components', f), 'utf8');

/** Литерал JS после `name =` до закрывающей скобки верхнего уровня. */
function literal(src, name) {
  const at = src.search(new RegExp(`(?:const|export const) ${name}\\b[^=]*=\\s*`));
  if (at < 0) throw new Error(`${name} not found`);
  const start = src.indexOf('=', at) + 1;
  let i = start;
  while (/\s/.test(src[i])) i++;
  const open = src[i];
  if (open === "'") return src.slice(i + 1, src.indexOf("'", i + 1));
  const close = open === '[' ? ']' : '}';
  let depth = 0, inStr = null;
  for (let j = i; j < src.length; j++) {
    const c = src[j];
    if (inStr) { if (c === inStr && src[j - 1] !== '\\') inStr = null; continue; }
    if (c === "'" || c === '"' || c === '`') { inStr = c; continue; }
    if (c === open) depth++;
    else if (c === close && --depth === 0) return Function(`return (${src.slice(i, j + 1)});`)();
  }
  throw new Error(`${name}: unbalanced`);
}

const logo = comp('LogoDie.tsx');
const glyphsSrc = comp('logo-die-glyphs.ts');
const icons = literal(comp('LoadingScreen.tsx'), 'ICONS');
const pool = literal(glyphsSrc, 'LOGO_GLYPH_POOL').filter((k) => k in icons);

const data = {
  p: literal(logo, 'P_GLYPH_D'),
  masks: literal(logo, 'MASKS_PATHS'),
  scroll: literal(logo, 'SCROLL_D'),
  pool: Object.fromEntries(pool.map((k) => [k, icons[k]])),
};
const out = `/* Generated by tools/promo-die-glyphs.mjs from magicorp-vtt — do not edit. */
window.RB_PROMO_DIE = ${JSON.stringify(data)};
`;
writeFileSync(new URL('../www/js/promo-die-glyphs.js', import.meta.url), out);
console.log(`promo-die-glyphs: P, ${data.masks.length} mask paths, ${data.scroll.length} scroll paths, ${pool.length} pool glyphs`);
